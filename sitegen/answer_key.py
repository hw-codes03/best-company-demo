"""Writes answer_key/ground_truth.csv: the true status of every image file on the site.

This is the HIDDEN answer key. A detection pipeline must never read it; it exists only
so a separate scoring step can measure how well the pipeline did.
"""

import csv

from . import config
from .personas import ALL_PERSONAS, PRIYA_NAIR
from .plan import hard_to_find

COLUMNS = [
    "image_path", "image_url", "drawn_locale", "style", "persona", "persona_status",
    "name_shown", "email_shown", "avatar_initials", "avatar_color", "is_outdated",
    "replace_with", "is_decoy", "pages", "load_methods", "reference_count",
    "only_on_hidden_pages", "only_lazy_loaded", "hard_to_find", "in_client_audit",
    "client_audit_rows",
]

README = """# Answer key: do not read from the pipeline

`ground_truth.csv` lists the true status of every image file in `site/`.

Any detection pipeline must never open this folder. Only a separate scoring step may
read it, to compare the pipeline's findings with the truth. It is generated by
`python3 generate.py` and is fully synthetic.
"""


def _yes_no(value):
    return "yes" if value else "no"


def write_ground_truth(plan, audit_rows):
    pages_by_path = {p.path: p for p in plan.pages}
    # Which client-audit row numbers mention each image (a duplicate shows up twice).
    audit_hits = {}
    for i, r in enumerate(audit_rows, start=1):
        audit_hits.setdefault(r.image_path, []).append(str(i))

    config.ANSWER_KEY_DIR.mkdir(exist_ok=True)
    (config.ANSWER_KEY_DIR / "README.md").write_text(README, encoding="utf-8")
    with open(config.GROUND_TRUTH_CSV, "w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow(COLUMNS)
        for a in sorted(plan.images, key=lambda a: a.path):
            persona = ALL_PERSONAS.get(a.persona_key)
            outdated = a.persona_key == "jordan_vale"
            writer.writerow([
                a.path,
                f"{config.BASE_URL}/{a.path}",
                a.locale,
                a.style,
                a.persona_key or "none",
                persona.status if persona else "no_person",
                a.name_shown or "",
                persona.email if persona else "",
                persona.initials if persona else "",
                persona.avatar_color_name if persona else "",
                _yes_no(outdated),
                PRIYA_NAIR.key if outdated else "",
                _yes_no(a.persona_key == "jordan_vail"),
                ";".join(p for p, _ in a.refs),
                ";".join(m for _, m in a.refs),
                len(a.refs),
                _yes_no(all(pages_by_path[p].hidden for p, _ in a.refs)),
                _yes_no(all(m == "data-src" for _, m in a.refs)),
                _yes_no(hard_to_find(a, pages_by_path)),
                _yes_no(a.path in audit_hits),
                ";".join(audit_hits.get(a.path, [])),
            ])
